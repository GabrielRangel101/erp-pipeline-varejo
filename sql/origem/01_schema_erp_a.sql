-- =====================================================================
-- 01_schema_erp_a.sql  —  ORIGEM: "ERP A" (ERP de varejo alimentar, SINTÉTICO)
-- Banco: erp_origem   |   Dono: erp_app   |   Leitura do pipeline: erp_ro
--
-- Imita um ERP legado típico. As "armadilhas" abaixo são DELIBERADAS: é o que
-- torna o incremental e a conferência de qualidade testes de verdade.
--
--  1. SEM chaves estrangeiras e quase sem NOT NULL: a integridade vive na
--     aplicação do ERP. Por isso existem itens órfãos, valores nulos etc.
--  2. dt_alt (carimbo de última alteração) é mantido por trigger no UPDATE,
--     mas a aplicação pode gravar um dt_alt antigo (importação, contingência
--     fiscal) => linhas que chegam "atrasadas" ficam ABAIXO da marca-d'água.
--  3. Cancelar uma venda atualiza só o CABEÇALHO (mov_venda.status = 'C');
--     os itens continuam 'N' e com dt_alt antigo. Extrair itens só por
--     dt_alt perde o cancelamento.
--  4. Valores em dinheiro/quantidade podem vir nulos, zerados, negativos ou
--     com total diferente de qtd*unit-desconto.
--  5. Nenhum dado pessoal. Sem CNPJ/CPF de propósito (um CNPJ gerado poderia
--     coincidir com o de uma empresa real). Códigos de barras usam o prefixo
--     200-299 do GS1, reservado para uso interno, que não colide com produto real.
--
-- Convenção: tp_mov  INV inventário | CMP compra | VND venda | DEV devolução/estorno
--                    AJT ajuste | PRD perda
--            sentido E entrada | S saída  (qtd é sempre positiva; o sinal vem do sentido)
-- =====================================================================

SET ROLE erp_app;
SET client_min_messages = warning;   -- silencia os avisos "já existe, ignorando" ao repetir

CREATE SCHEMA IF NOT EXISTS erp;
SET search_path = erp;

-- ---------- Cadastros ------------------------------------------------

CREATE TABLE IF NOT EXISTS cad_fornecedor (
    cod_fornecedor  integer       PRIMARY KEY,
    razao_social    varchar(120)  NOT NULL,
    uf              char(2),
    ativo           boolean       NOT NULL DEFAULT true,
    dt_cadastro     date          NOT NULL DEFAULT current_date,
    dt_alt          timestamp     NOT NULL DEFAULT localtimestamp
);

CREATE TABLE IF NOT EXISTS cad_loja (
    cod_loja        smallint      PRIMARY KEY,
    nome_loja       varchar(80)   NOT NULL,
    cidade          varchar(60),
    uf              char(2),
    formato         varchar(20),              -- HIPER | SUPER | EXPRESS
    dt_abertura     date,
    ativa           boolean       NOT NULL DEFAULT true,
    dt_alt          timestamp     NOT NULL DEFAULT localtimestamp
);

CREATE TABLE IF NOT EXISTS cad_produto (
    cod_produto     integer       PRIMARY KEY,
    cod_barras      varchar(14),
    descricao       varchar(120)  NOT NULL,
    departamento    varchar(40),
    secao           varchar(40),
    unid_medida     char(2),                  -- UN | KG
    cod_fornecedor  integer,                  -- sem FK (armadilha 1)
    preco_venda     numeric(12,2),
    custo_medio     numeric(12,4),
    ativo           boolean       NOT NULL DEFAULT true,
    dt_alt          timestamp     NOT NULL DEFAULT localtimestamp
);

-- ---------- Vendas ---------------------------------------------------

CREATE TABLE IF NOT EXISTS mov_venda (
    id_venda        bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_loja        smallint,
    nr_caixa        smallint,
    nr_cupom        integer,
    dt_venda        timestamp     NOT NULL,
    status          char(1)       NOT NULL DEFAULT 'F',   -- F finalizada | C cancelada
    vl_bruto        numeric(14,2),
    vl_desconto     numeric(14,2),
    vl_total        numeric(14,2),
    forma_pagto     varchar(15),                          -- DINHEIRO | CREDITO | DEBITO | PIX | VOUCHER
    dt_alt          timestamp     NOT NULL DEFAULT localtimestamp
);

CREATE TABLE IF NOT EXISTS mov_venda_item (
    id_item         bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venda        bigint,                   -- sem FK: pode apontar para venda inexistente
    nr_item         smallint,
    cod_produto     integer,                  -- sem FK: pode apontar para produto inexistente
    qtd             numeric(12,3),
    vl_unit         numeric(12,2),
    vl_desconto     numeric(12,2) NOT NULL DEFAULT 0,
    vl_total        numeric(14,2),            -- deveria ser qtd*vl_unit - vl_desconto (armadilha 4)
    vl_custo_unit   numeric(12,4),            -- custo no momento da venda (base da margem)
    status_item     char(1)       NOT NULL DEFAULT 'N',   -- N normal | C item cancelado no cupom
    dt_alt          timestamp     NOT NULL DEFAULT localtimestamp
);

-- ---------- Estoque --------------------------------------------------

CREATE TABLE IF NOT EXISTS mov_estoque (
    id_mov          bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_loja        smallint,
    cod_produto     integer,
    dt_mov          timestamp     NOT NULL,
    tp_mov          varchar(3)    NOT NULL,   -- INV | CMP | VND | DEV | AJT | PRD
    sentido         char(1)       NOT NULL,   -- E | S
    qtd             numeric(12,3),
    doc_origem      varchar(20),              -- id da venda/compra que gerou o movimento
    dt_alt          timestamp     NOT NULL DEFAULT localtimestamp
);

-- ---------- Compras --------------------------------------------------

CREATE TABLE IF NOT EXISTS mov_compra (
    id_compra       bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_loja        smallint,
    cod_fornecedor  integer,
    nr_nf           varchar(20),
    dt_emissao      date,
    dt_entrada      timestamp,
    status          char(1)       NOT NULL DEFAULT 'R',   -- R recebida | P pendente | C cancelada
    vl_total        numeric(14,2),
    dt_alt          timestamp     NOT NULL DEFAULT localtimestamp
);

CREATE TABLE IF NOT EXISTS mov_compra_item (
    id_compra_item  bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra       bigint,
    cod_produto     integer,
    qtd             numeric(12,3),
    vl_custo_unit   numeric(12,4),
    vl_total        numeric(14,2),
    dt_alt          timestamp     NOT NULL DEFAULT localtimestamp
);

-- ---------- Índices --------------------------------------------------
-- Pré-requisito para integrar qualquer ERP: índice em dt_alt. Sem ele, cada
-- carga incremental vira leitura da tabela inteira (ver README, "Como eu integraria").
CREATE INDEX IF NOT EXISTS ix_fornecedor_dt_alt   ON cad_fornecedor  (dt_alt);
CREATE INDEX IF NOT EXISTS ix_loja_dt_alt         ON cad_loja        (dt_alt);
CREATE INDEX IF NOT EXISTS ix_produto_dt_alt      ON cad_produto     (dt_alt);
CREATE INDEX IF NOT EXISTS ix_venda_dt_alt        ON mov_venda       (dt_alt);
CREATE INDEX IF NOT EXISTS ix_venda_item_dt_alt   ON mov_venda_item  (dt_alt);
CREATE INDEX IF NOT EXISTS ix_estoque_dt_alt      ON mov_estoque     (dt_alt);
CREATE INDEX IF NOT EXISTS ix_compra_dt_alt       ON mov_compra      (dt_alt);
CREATE INDEX IF NOT EXISTS ix_compra_item_dt_alt  ON mov_compra_item (dt_alt);
-- Apoio à conferência por dia e loja e à busca de itens por venda.
CREATE INDEX IF NOT EXISTS ix_venda_dt_venda      ON mov_venda       (dt_venda, cod_loja);
CREATE INDEX IF NOT EXISTS ix_venda_item_venda    ON mov_venda_item  (id_venda);

-- ---------- Trigger de dt_alt ----------------------------------------
-- No UPDATE, se a aplicação não informou um dt_alt novo, o "ERP" carimba a hora
-- atual. Se informou (importação/contingência), respeita => linha atrasada.
CREATE OR REPLACE FUNCTION tg_toca_dt_alt() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.dt_alt IS NOT DISTINCT FROM OLD.dt_alt THEN
        NEW.dt_alt := localtimestamp;
    END IF;
    RETURN NEW;
END $$;

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['cad_fornecedor','cad_loja','cad_produto','mov_venda',
                             'mov_venda_item','mov_estoque','mov_compra','mov_compra_item']
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS tg_dt_alt ON erp.%I', t);
        EXECUTE format('CREATE TRIGGER tg_dt_alt BEFORE UPDATE ON erp.%I
                        FOR EACH ROW EXECUTE FUNCTION erp.tg_toca_dt_alt()', t);
    END LOOP;
END $$;

-- ---------- Permissões do pipeline: SOMENTE LEITURA ------------------
REVOKE ALL ON SCHEMA erp FROM PUBLIC;
GRANT USAGE ON SCHEMA erp TO erp_ro;
GRANT SELECT ON ALL TABLES IN SCHEMA erp TO erp_ro;
ALTER DEFAULT PRIVILEGES IN SCHEMA erp GRANT SELECT ON TABLES TO erp_ro;
